/// Cabal 3.18.1.0 renders this module from Distribution/Simple/Build/PathsModule/Z.hs for an installed library on Linux.
pub fn module(module: &str, prefix: &str, version: &str) -> String {
    let name = module.strip_prefix("Paths_").unwrap_or(module);
    let digits = format!("[{}]", version.replace('.', ","));
    TEMPLATE
        .replace("@NAME@", name)
        .replace("@DIGITS@", &digits)
        .replace("@PREFIX@", prefix)
}
