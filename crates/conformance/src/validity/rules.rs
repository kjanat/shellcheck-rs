use std::fmt::Write;

use shellcheck_rs::Dialect;

use super::matrix::{self, Matrix, version_cmp};
use super::outcomes::{self, Outcome, Outcomes};

pub fn run() -> Result<(), String> {
    let text = render(&outcomes::load()?, &matrix::load()?)?;
    std::fs::write(super::RULES, text).map_err(|e| format!("{}: {e}", super::RULES))
}

pub fn render(outcomes: &Outcomes, matrix: &Matrix) -> Result<String, String> {
    let mut rules: Vec<(i64, Dialect, &str, Outcome)> = Vec::new();
    for row in &outcomes.row {
        let cell = matrix.find(&row.shell, &row.version).ok_or_else(|| {
            format!(
                "{}: no cell {}:{} in {}",
                super::OUTCOMES,
                row.shell,
                row.version,
                super::MATRIX
            )
        })?;
        let Some(dialect) = Dialect::from_name(&cell.shell).filter(|d| d.is_added()) else {
            continue;
        };
        rules.push((row.code, dialect, row.version.as_str(), row.outcome));
    }
    rules.sort_by(|a, b| {
        a.0.cmp(&b.0)
            .then_with(|| a.1.name().cmp(b.1.name()))
            .then_with(|| version_cmp(a.2, b.2))
    });
    let mut out =
        String::from("// Generated by `cargo validity rules` from validity/outcomes.toml.\n\n");
    if rules.is_empty() {
        out.push_str("pub const RULES: &[crate::dialect_policy::Rule] = &[];\n");
        return Ok(out);
    }
    out.push_str(
        "use crate::dialect::Dialect;\n\
         use crate::dialect_policy::{Outcome, Rule};\n\n\
         pub const RULES: &[Rule] = &[\n",
    );
    for (code, dialect, version, outcome) in rules {
        let _ = writeln!(
            out,
            "    Rule {{\n        code: {code},\n        dialect: Dialect::{dialect:?},\n        \
             version: {version:?},\n        outcome: Outcome::{outcome:?},\n    }},"
        );
    }
    out.push_str("];\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;
    use crate::validity::matrix::{Cell, SourcePin};
    use crate::validity::outcomes::Row;

    fn cell(shell: &str, version: &str, dialect: Option<&str>) -> Cell {
        Cell {
            shell: shell.to_string(),
            version: version.to_string(),
            image: String::new(),
            digest: String::new(),
            base: String::new(),
            dockerfile: shell.to_string(),
            argv: vec![shell.to_string()],
            parse: vec!["-n".to_string()],
            shipped: dialect.is_some(),
            vm: false,
            dialect: dialect.map(str::to_string),
            source: SourcePin::Crate {
                version: version.to_string(),
            },
        }
    }

    fn row(code: i64, shell: &str, version: &str, outcome: Outcome) -> Row {
        Row {
            code,
            shell: shell.to_string(),
            version: version.to_string(),
            outcome,
            observed: String::new(),
        }
    }

    #[test]
    fn only_added_dialect_cells_reach_the_table_sorted_by_code_dialect_version() {
        let matrix = Matrix {
            cell: vec![
                cell("bash", "5.3", Some("bash")),
                cell("zsh", "5.9", None),
                cell("zsh", "5.10", None),
                cell("zsh-sh", "5.9", Some("sh")),
                cell("tcsh", "6.24.16", None),
                cell("mksh", "R59c", None),
            ],
        };
        let mut outcomes = Outcomes::default();
        outcomes.merge(&[
            row(2086, "zsh", "5.10", Outcome::Absent),
            row(2086, "zsh", "5.9", Outcome::Absent),
            row(2086, "bash", "5.3", Outcome::Reproduces),
            row(2086, "zsh-sh", "5.9", Outcome::Reproduces),
            row(2086, "tcsh", "6.24.16", Outcome::Differs),
            row(2046, "mksh", "R59c", Outcome::PortMiss),
        ]);
        let text = render(&outcomes, &matrix).unwrap();
        assert_eq!(
            text,
            "// Generated by `cargo validity rules` from validity/outcomes.toml.\n\
             \n\
             use crate::dialect::Dialect;\n\
             use crate::dialect_policy::{Outcome, Rule};\n\
             \n\
             pub const RULES: &[Rule] = &[\n\
             \x20   Rule {\n\
             \x20       code: 2046,\n\
             \x20       dialect: Dialect::Mksh,\n\
             \x20       version: \"R59c\",\n\
             \x20       outcome: Outcome::PortMiss,\n\
             \x20   },\n\
             \x20   Rule {\n\
             \x20       code: 2086,\n\
             \x20       dialect: Dialect::Zsh,\n\
             \x20       version: \"5.9\",\n\
             \x20       outcome: Outcome::Absent,\n\
             \x20   },\n\
             \x20   Rule {\n\
             \x20       code: 2086,\n\
             \x20       dialect: Dialect::Zsh,\n\
             \x20       version: \"5.10\",\n\
             \x20       outcome: Outcome::Absent,\n\
             \x20   },\n\
             ];\n"
        );
    }

    #[test]
    fn a_row_without_a_cell_is_an_error_and_no_rows_give_an_empty_table() {
        let matrix = Matrix {
            cell: vec![cell("bash", "5.3", Some("bash"))],
        };
        let mut outcomes = Outcomes::default();
        outcomes.merge(&[row(2086, "zsh", "5.9", Outcome::Absent)]);
        let err = render(&outcomes, &matrix).unwrap_err();
        assert!(err.contains("no cell zsh:5.9"), "{err}");
        let text = render(&Outcomes::default(), &matrix).unwrap();
        assert_eq!(
            text,
            "// Generated by `cargo validity rules` from validity/outcomes.toml.\n\n\
             pub const RULES: &[crate::dialect_policy::Rule] = &[];\n"
        );
    }

    #[test]
    fn the_committed_table_is_what_the_committed_outcomes_render() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let outcomes = outcomes::load_from(&root.join(crate::validity::OUTCOMES)).unwrap();
        let matrix = matrix::load_from(&root.join(crate::validity::MATRIX)).unwrap();
        let committed = std::fs::read_to_string(root.join(crate::validity::RULES)).unwrap();
        assert_eq!(render(&outcomes, &matrix).unwrap(), committed);
    }
}
