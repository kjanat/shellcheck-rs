use std::cmp::Ordering;
use std::path::Path;

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use shellcheck_rs::Dialect;

#[derive(Serialize, Deserialize, JsonSchema, Default)]
pub struct Matrix {
    #[serde(default)]
    pub cell: Vec<Cell>,
}

#[derive(Serialize, Deserialize, JsonSchema, Clone)]
pub struct Cell {
    pub shell: String,
    pub version: String,
    pub image: String,
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub digest: String,
    pub base: String,
    pub dockerfile: String,
    pub argv: Vec<String>,
    pub parse: Vec<String>,
    pub shipped: bool,
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub vm: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub dialect: Option<String>,
    pub source: SourcePin,
}

#[derive(Serialize, Deserialize, JsonSchema, Clone, PartialEq, Eq, Debug)]
#[serde(tag = "kind", rename_all = "lowercase")]
pub enum SourcePin {
    Tarball {
        url: String,
        sha256: String,
    },
    Git {
        repo: String,
        tag: String,
        commit: String,
    },
    Crate {
        version: String,
    },
    Image {
        url: String,
        sha256: String,
    },
}

impl SourcePin {
    pub fn build_args(&self) -> Vec<(&'static str, &str)> {
        match self {
            Self::Tarball { url, sha256 } => {
                vec![("KIND", "tarball"), ("SOURCE", url), ("SHA256", sha256)]
            }
            Self::Git { repo, tag, commit } => {
                vec![
                    ("KIND", "git"),
                    ("SOURCE", repo),
                    ("TAG", tag),
                    ("COMMIT", commit),
                ]
            }
            Self::Crate { .. } => vec![("KIND", "crate")],
            Self::Image { url, sha256 } => {
                vec![("KIND", "image"), ("SOURCE", url), ("SHA256", sha256)]
            }
        }
    }
}

impl Cell {
    pub fn id(&self) -> String {
        format!("{}:{}", self.shell, self.version)
    }

    pub fn port_shell(&self) -> Option<&str> {
        self.dialect
            .as_deref()
            .or_else(|| Dialect::from_name(&self.shell).map(Dialect::name))
    }

    pub fn matches(&self, filters: &[String]) -> bool {
        filters.is_empty() || filters.iter().any(|f| *f == self.shell || *f == self.id())
    }

    pub fn reference(&self) -> String {
        if self.digest.is_empty() {
            return self.image.clone();
        }
        let repo = self
            .image
            .rsplit_once(':')
            .map_or(self.image.as_str(), |(r, _)| r);
        format!("{repo}@{}", self.digest)
    }
}

impl Matrix {
    pub fn cells<'a>(&'a self, filters: &'a [String]) -> impl Iterator<Item = &'a Cell> {
        self.cell.iter().filter(move |c| c.matches(filters))
    }

    pub fn find(&self, shell: &str, version: &str) -> Option<&Cell> {
        self.cell
            .iter()
            .find(|c| c.shell == shell && c.version == version)
    }

    pub fn sort(&mut self) {
        self.cell.sort_by(|a, b| {
            a.shell
                .cmp(&b.shell)
                .then_with(|| version_cmp(&a.version, &b.version))
        });
    }
}

pub fn version_cmp(a: &str, b: &str) -> Ordering {
    let parts = |s: &str| -> Vec<(u64, String)> {
        s.split(['.', '-', '_'])
            .map(|p| (p.parse::<u64>().unwrap_or(u64::MAX), p.to_string()))
            .collect()
    };
    parts(a).cmp(&parts(b))
}

pub fn load() -> Result<Matrix, String> {
    load_from(Path::new(super::MATRIX))
}

pub fn load_from(path: &Path) -> Result<Matrix, String> {
    match std::fs::read_to_string(path) {
        Ok(text) => toml::from_str(&text).map_err(|e| format!("{}: {e}", path.display())),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Matrix::default()),
        Err(e) => Err(format!("{}: {e}", path.display())),
    }
}

pub fn save(matrix: &Matrix) -> Result<(), String> {
    save_to(Path::new(super::MATRIX), matrix)
}

pub fn save_to(path: &Path, matrix: &Matrix) -> Result<(), String> {
    std::fs::write(path, text(matrix)?).map_err(|e| format!("{}: {e}", path.display()))
}

fn text(matrix: &Matrix) -> Result<String, String> {
    let body = toml::to_string(matrix).map_err(|e| e.to_string())?;
    Ok(format!(
        "#:schema ../schemas/validity-matrix.schema.json\n\
         # Generated by `cargo validity pin` from sources.toml.\n\n{body}"
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cell(shell: &str, version: &str) -> Cell {
        Cell {
            shell: shell.to_string(),
            version: version.to_string(),
            image: format!("ghcr.io/x/shell-{shell}:{version}"),
            digest: String::new(),
            base: "debian@sha256:0".to_string(),
            dockerfile: shell.to_string(),
            argv: vec![shell.to_string()],
            parse: vec!["-n".to_string()],
            shipped: true,
            vm: false,
            dialect: Some(shell.to_string()),
            source: SourcePin::Tarball {
                url: "u".to_string(),
                sha256: "s".to_string(),
            },
        }
    }

    #[test]
    fn versions_sort_numerically() {
        assert_eq!(version_cmp("0.5.9.1", "0.5.10.2"), Ordering::Less);
        assert_eq!(version_cmp("1.37.0", "1.4.0"), Ordering::Greater);
        assert_eq!(version_cmp("R59c", "R59c"), Ordering::Equal);
    }

    #[test]
    fn filters_match_shell_or_id() {
        let c = cell("bash", "5.3");
        assert!(c.matches(&[]));
        assert!(c.matches(&["bash".to_string()]));
        assert!(c.matches(&["bash:5.3".to_string()]));
        assert!(!c.matches(&["bash:5.2".to_string()]));
    }

    #[test]
    fn a_digest_replaces_the_tag() {
        let mut c = cell("bash", "5.3");
        assert_eq!(c.reference(), "ghcr.io/x/shell-bash:5.3");
        c.digest = "sha256:abc".to_string();
        assert_eq!(c.reference(), "ghcr.io/x/shell-bash@sha256:abc");
    }

    #[test]
    fn the_file_round_trips() {
        let dir = std::env::temp_dir().join(format!("validity-matrix-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.join("matrix.toml");
        let mut guest = cell("netbsd-sh", "11.0");
        guest.vm = true;
        let mut m = Matrix {
            cell: vec![cell("dash", "0.5.12"), cell("bash", "5.3"), guest],
        };
        m.sort();
        save_to(&path, &m).unwrap();
        let text = std::fs::read_to_string(&path).unwrap();
        let back = load_from(&path).unwrap();
        std::fs::remove_dir_all(&dir).unwrap();
        assert_eq!(back.cell[0].shell, "bash");
        assert_eq!(back.cell[1].source, m.cell[1].source);
        assert_eq!(text.matches("vm = true").count(), 1);
        assert!(text.starts_with("#:schema ../schemas/validity-matrix.schema.json\n# Generated"));
        assert!(back.cell[2].vm);
        assert!(!back.cell[0].vm);
        assert!(
            load_from(Path::new("/nonexistent/matrix.toml"))
                .unwrap()
                .cell
                .is_empty()
        );
    }

    #[test]
    fn the_checked_in_matrix_is_writer_output() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .join(crate::validity::MATRIX);
        let written = std::fs::read_to_string(&path).unwrap();
        assert_eq!(text(&load_from(&path).unwrap()).unwrap(), written);
    }
}
