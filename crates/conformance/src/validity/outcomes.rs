use std::collections::BTreeMap;
use std::fmt::Write;
use std::path::Path;

use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

use super::matrix::{Matrix, version_cmp};
use super::spec::Spec;

#[derive(Serialize, Deserialize, JsonSchema, Default)]
pub struct Outcomes {
    #[serde(default)]
    pub row: Vec<Row>,
}

#[derive(Serialize, Deserialize, JsonSchema, Clone, PartialEq, Eq)]
pub struct Row {
    pub code: i64,
    pub shell: String,
    pub version: String,
    pub outcome: Outcome,
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub observed: String,
}

#[derive(Serialize, Deserialize, JsonSchema, Clone, Copy, PartialEq, Eq, Debug)]
#[serde(rename_all = "kebab-case")]
pub enum Outcome {
    Reproduces,
    Absent,
    Differs,
    Unparsable,
    Timeout,
    PortMiss,
}

impl Outcome {
    pub const ALL: [Self; 6] = [
        Self::Reproduces,
        Self::Absent,
        Self::Differs,
        Self::Unparsable,
        Self::Timeout,
        Self::PortMiss,
    ];

    pub const fn label(self) -> &'static str {
        match self {
            Self::Reproduces => "reproduces",
            Self::Absent => "absent",
            Self::Differs => "differs",
            Self::Unparsable => "unparsable",
            Self::Timeout => "timeout",
            Self::PortMiss => "port-miss",
        }
    }
}

impl Row {
    pub fn same_cell(&self, other: &Self) -> bool {
        self.code == other.code && self.shell == other.shell && self.version == other.version
    }
}

impl Outcomes {
    pub fn retain_current(&mut self, specs: &[Spec], matrix: &Matrix) {
        self.row.retain(|row| {
            specs.iter().any(|spec| spec.code == row.code)
                && matrix.find(&row.shell, &row.version).is_some()
        });
    }

    pub fn merge(&mut self, rows: &[Row]) {
        for row in rows {
            match self.row.iter_mut().find(|r| r.same_cell(row)) {
                Some(existing) => *existing = row.clone(),
                None => self.row.push(row.clone()),
            }
        }
        self.row.sort_by(|a, b| {
            a.code
                .cmp(&b.code)
                .then_with(|| a.shell.cmp(&b.shell))
                .then_with(|| version_cmp(&a.version, &b.version))
        });
    }

    pub fn find(&self, row: &Row) -> Option<&Row> {
        self.row.iter().find(|r| r.same_cell(row))
    }
}

pub fn load() -> Result<Outcomes, String> {
    load_from(Path::new(super::OUTCOMES))
}

pub fn load_from(path: &Path) -> Result<Outcomes, String> {
    match std::fs::read_to_string(path) {
        Ok(text) => toml::from_str(&text).map_err(|e| format!("{}: {e}", path.display())),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(Outcomes::default()),
        Err(e) => Err(format!("{}: {e}", path.display())),
    }
}

pub fn save(outcomes: &Outcomes, specs: &[Spec]) -> Result<(), String> {
    std::fs::write(super::OUTCOMES, text(outcomes)?)
        .map_err(|e| format!("{}: {e}", super::OUTCOMES))?;
    std::fs::write(super::REPORT, report(outcomes, specs))
        .map_err(|e| format!("{}: {e}", super::REPORT))
}

fn text(outcomes: &Outcomes) -> Result<String, String> {
    let body = toml::to_string(outcomes).map_err(|e| e.to_string())?;
    Ok(format!(
        "#:schema ../schemas/validity-outcomes.schema.json\n\
         # Generated by `cargo validity --record`.\n\n{body}"
    ))
}

pub fn report(outcomes: &Outcomes, specs: &[Spec]) -> String {
    let mut out = String::from(
        "# Validity report\n\nGenerated by `cargo validity --record`. One section per spec; \
         each outcome lists the cells that produced it.\n",
    );
    for spec in specs {
        let _ = write!(out, "\n## SC{}\n\nClaim: {}.\n\n", spec.code, spec.claim);
        let mut by_outcome: BTreeMap<&str, Vec<String>> = BTreeMap::new();
        for row in outcomes.row.iter().filter(|r| r.code == spec.code) {
            by_outcome
                .entry(row.outcome.label())
                .or_default()
                .push(format!("{} {}", row.shell, row.version));
        }
        for outcome in Outcome::ALL {
            if let Some(cells) = by_outcome.get(outcome.label()) {
                let _ = writeln!(out, "- {}: {}", outcome.label(), cells.join(", "));
            }
        }
        for row in outcomes
            .row
            .iter()
            .filter(|r| r.code == spec.code && !r.observed.is_empty())
        {
            let _ = writeln!(
                out,
                "  - {} {}: `{}`",
                row.shell,
                row.version,
                row.observed.replace('\n', "\\n")
            );
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::validity::spec::{Observe, Script};

    fn row(code: i64, shell: &str, version: &str, outcome: Outcome) -> Row {
        Row {
            code,
            shell: shell.to_string(),
            version: version.to_string(),
            outcome,
            observed: String::new(),
        }
    }

    #[test]
    fn merge_replaces_matching_rows_and_sorts() {
        let mut o = Outcomes {
            row: vec![row(2086, "bash", "5.3", Outcome::Reproduces)],
        };
        o.merge(&[
            row(2086, "bash", "5.3", Outcome::Absent),
            row(2046, "dash", "0.5.12", Outcome::Reproduces),
            row(2086, "bash", "4.4.18", Outcome::Reproduces),
        ]);
        let ids: Vec<_> = o
            .row
            .iter()
            .map(|r| format!("{} {} {}", r.code, r.shell, r.version))
            .collect();
        assert_eq!(
            ids,
            ["2046 dash 0.5.12", "2086 bash 4.4.18", "2086 bash 5.3"]
        );
        assert_eq!(o.row[2].outcome, Outcome::Absent);
    }

    #[test]
    fn the_report_groups_cells_by_outcome() {
        let spec = Spec {
            code: 2086,
            claim: "splits".to_string(),
            shell: None,
            snippet: Script {
                script: String::new(),
            },
            fixed: Script {
                script: String::new(),
            },
            observe: vec![Observe {
                kind: crate::validity::spec::Kind::Stdout,
                snippet: String::new(),
                fixed: String::new(),
            }],
        };
        let mut o = Outcomes::default();
        o.merge(&[
            row(2086, "bash", "5.3", Outcome::Reproduces),
            row(2086, "zsh", "5.9", Outcome::Absent),
            Row {
                observed: "x\ny".to_string(),
                ..row(2086, "osh", "0.38.0", Outcome::Differs)
            },
        ]);
        let text = report(&o, &[spec]);
        assert!(text.contains("## SC2086"));
        assert!(text.contains("- reproduces: bash 5.3\n"));
        assert!(text.contains("- absent: zsh 5.9\n"));
        assert!(text.contains("  - osh 0.38.0: `x\\ny`\n"));
    }

    #[test]
    fn the_checked_in_outcomes_are_writer_output() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .join(crate::validity::OUTCOMES);
        let written = std::fs::read_to_string(&path).unwrap();
        let text = text(&load_from(&path).unwrap()).unwrap();
        assert!(text.starts_with("#:schema ../schemas/validity-outcomes.schema.json\n# Generated"));
        assert_eq!(text, written);
    }
}
